"""Build a small sample .ufp (Cura package) for testing: python -m tests.make_sample out.ufp [machine] [seconds]"""
import io, sys, zipfile
from simulator.sim_printer import _png

def make(machine="Ultimaker S5", seconds=3600, guid="2f9d2279-9b0e-4765-bf9b-d1e1e13f3c49"):
    header = f""";START_OF_HEADER
;HEADER_VERSION:0.1
;FLAVOR:Griffin
;GENERATOR.NAME:Cura_SteamEngine
;TARGET_MACHINE.NAME:{machine}
;EXTRUDER_TRAIN.0.INITIAL_TEMPERATURE:210
;EXTRUDER_TRAIN.0.MATERIAL.VOLUME_USED:4321
;EXTRUDER_TRAIN.0.MATERIAL.GUID:{guid}
;EXTRUDER_TRAIN.0.NOZZLE.DIAMETER:0.4
;EXTRUDER_TRAIN.0.NOZZLE.NAME:AA 0.4
;PRINT.TIME:{seconds}
;PRINT.GROUPS:1
;END_OF_HEADER
G28
"""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("3D/model.gcode", header + "G1 X10 Y10\n" * 200)
        z.writestr("Metadata/thumbnail.png", _png(120, 120, 0.5))
        z.writestr("[Content_Types].xml", "<Types/>")
    return buf.getvalue()

if __name__ == "__main__":
    out = sys.argv[1]
    open(out, "wb").write(make(*(sys.argv[2:3] or ["Ultimaker S5"]), int(sys.argv[3]) if len(sys.argv) > 3 else 3600))
    print("wrote", out)


def make_cura_marlin(machine="ELEGOO NEPTUNE 4 PRO", seconds=1800):
    """Cura slicing for a non-Ultimaker printer (Marlin flavour)."""
    return (f";FLAVOR:Marlin\n;TIME:{seconds}\n;Filament used: 1.2m\n;Layer height: 0.2\n"
            f";TARGET_MACHINE.NAME:{machine}\n;Generated with Cura_SteamEngine 5.8.1\nG28\n"
            + "G1 X10 Y10\n" * 200).encode()


def make_orca(printer_model="Elegoo Centauri Carbon", minutes=30):
    """OrcaSlicer / ElegooSlicer style: header block, embedded thumbnail, config block at the end."""
    import base64
    png = base64.b64encode(_png(96, 96, 0.3)).decode()
    thumb = "\n".join("; " + png[i:i + 78] for i in range(0, len(png), 78))
    head = (f"; HEADER_BLOCK_START\n; generated by ElegooSlicer 1.1.0\n; total layer number: 150\n"
            f"; total estimated time: {minutes}m 0s\n; HEADER_BLOCK_END\n\n"
            f"; THUMBNAIL_BLOCK_START\n; thumbnail begin 96x96 {len(png)}\n{thumb}\n; thumbnail end\n; THUMBNAIL_BLOCK_END\n")
    body = "G1 X10 Y10\n" * 60000  # push the config block past the head window
    tail = (f"; CONFIG_BLOCK_START\n; printer_model = {printer_model}\n"
            f"; printer_settings_id = {printer_model} 0.4 nozzle\n; CONFIG_BLOCK_END\n")
    return (head + body + tail).encode()
