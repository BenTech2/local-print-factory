"""Read metadata out of print files: .ufp (Cura's zip package), .gcode, .gcode.gz.

Cura writes a Griffin header at the top of the gcode for Ultimaker printers:
    ;START_OF_HEADER
    ;PRINT.TIME:5432
    ;TARGET_MACHINE.NAME:Ultimaker S5
    ;EXTRUDER_TRAIN.0.MATERIAL.GUID:...
    ;EXTRUDER_TRAIN.0.NOZZLE.NAME:AA 0.4
    ;END_OF_HEADER
"""
import base64
import binascii
import gzip
import io
import re
import zipfile

ALLOWED_EXT = (".ufp", ".gcode", ".gcode.gz")
HEAD = 512 * 1024   # thumbnails + header live at the top
TAIL = 96 * 1024    # Orca/Prusa write their settings block at the end


def allowed(filename: str) -> bool:
    return filename.lower().endswith(ALLOWED_EXT)


def _parse_header(text: str) -> dict:
    meta = {"extruders": {}}
    for line in text.splitlines()[:600]:
        if line.startswith(";END_OF_HEADER"):
            break
        m = re.match(r";([A-Z0-9_.]+):(.*)", line.strip())
        if not m:
            continue
        key, val = m.group(1), m.group(2).strip()
        if key == "PRINT.TIME":
            meta["print_time"] = int(float(val))
        elif key == "TARGET_MACHINE.NAME":
            meta["machine"] = val
        elif key == "FLAVOR":
            meta["flavor"] = val
        elif key == "PRINT.GROUPS":
            meta["groups"] = val
        elif key == "SLICE_UUID":
            meta["slice_uuid"] = val
        else:
            em = re.match(r"EXTRUDER_TRAIN\.(\d+)\.(.+)", key)
            if em:
                idx, sub = em.group(1), em.group(2)
                ex = meta["extruders"].setdefault(idx, {})
                if sub == "MATERIAL.GUID":
                    ex["material_guid"] = val
                elif sub == "NOZZLE.NAME":
                    ex["nozzle"] = val
                elif sub == "MATERIAL.VOLUME_USED":
                    try:
                        ex["volume_mm3"] = float(val)
                    except ValueError:
                        pass
                elif sub == "NOZZLE.DIAMETER":
                    ex["nozzle_diameter"] = val
    return meta


def _parse_slicer_comments(head: str, tail: str, meta: dict):
    """Fill in machine / time for non-Griffin gcode: Cura (Marlin flavour), OrcaSlicer,
    ElegooSlicer, PrusaSlicer and SuperSlicer."""
    text = head + "\n" + tail
    if "machine" not in meta:
        m = (re.search(r"^;\s*printer_model\s*=\s*(.+)$", text, re.M) or
             re.search(r"^;TARGET_MACHINE\.NAME:(.+)$", text, re.M) or
             re.search(r"^;\s*printer_settings_id\s*=\s*(.+)$", text, re.M))
        if m and m.group(1).strip():
            # "Elegoo Centauri Carbon 0.4 nozzle" -> "Elegoo Centauri Carbon"
            meta["machine"] = re.sub(r"\s*\(?\d+(\.\d+)?\s*(mm\s*)?nozzle\)?.*$", "", m.group(1).strip().strip('"'), flags=re.I)
    if "print_time" not in meta:
        m = re.search(r"^;TIME:(\d+)", text, re.M)
        if m:
            meta["print_time"] = int(m.group(1))
        else:
            m = (re.search(r"total estimated time:\s*([0-9dhms ]+)", text) or
                 re.search(r"estimated printing time \(normal mode\)\s*=\s*([0-9dhms ]+)", text))
            if m:
                secs = 0
                for n, unit in re.findall(r"(\d+)\s*([dhms])", m.group(1)):
                    secs += int(n) * {"d": 86400, "h": 3600, "m": 60, "s": 1}[unit]
                meta["print_time"] = secs
    m = re.search(r"^;\s*(?:generated by|Generated with)\s+(\S+)", head, re.M | re.I)
    if m:
        meta.setdefault("slicer", m.group(1))
    if "flavor" not in meta:
        m = re.search(r"^;FLAVOR:(\S+)", head, re.M)
        if m:
            meta["flavor"] = m.group(1)


def _embedded_thumbnail(text: str):
    """PrusaSlicer/Orca/Elegoo/Cura-plugin style '; thumbnail begin WxH len' base64 blocks. Largest wins."""
    best = None
    for m in re.finditer(r"; thumbnail(?:_\w+)? begin (\d+)x(\d+) \d+\s*\n(.*?)\n; thumbnail(?:_\w+)? end",
                         text, re.S):
        area = int(m.group(1)) * int(m.group(2))
        if best is None or area > best[0]:
            best = (area, m.group(3))
    if not best:
        return None
    try:
        return base64.b64decode("".join(line.lstrip("; ").strip() for line in best[1].splitlines()))
    except (ValueError, binascii.Error):
        return None


def extract_metadata(filename: str, data: bytes):
    """Returns (meta dict, thumbnail image bytes or None)."""
    name = filename.lower()
    thumb = None
    gcode_head = gcode_tail = ""
    try:
        if name.endswith(".ufp"):
            with zipfile.ZipFile(io.BytesIO(data)) as z:
                for n in z.namelist():
                    low = n.lower()
                    if low.endswith(".png") and "thumbnail" in low and thumb is None:
                        thumb = z.read(n)
                    elif low.endswith(".gcode") and not gcode_head:
                        with z.open(n) as f:
                            gcode_head = f.read(HEAD).decode("utf-8", "replace")
        else:
            raw = gzip.decompress(data) if name.endswith(".gcode.gz") else data
            gcode_head = raw[:HEAD].decode("utf-8", "replace")
            gcode_tail = raw[-TAIL:].decode("utf-8", "replace") if len(raw) > HEAD else ""
    except (zipfile.BadZipFile, OSError, EOFError) as e:
        return {"extruders": {}, "warning": f"Could not read file: {e}"}, None
    meta = _parse_header(gcode_head)
    _parse_slicer_comments(gcode_head, gcode_tail, meta)
    if thumb is None:
        thumb = _embedded_thumbnail(gcode_head)
    if not gcode_head:
        meta["warning"] = "No gcode found inside the file."
    elif "machine" not in meta:
        meta["warning"] = ("The file doesn't say which printer it was sliced for, so it can only be sent "
                           "to a printer you choose.")
    return meta, thumb
